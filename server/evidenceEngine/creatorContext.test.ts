import assert from 'node:assert/strict';
import test from 'node:test';
import { hasMeaningfulCreatorFields, hasMeaningfulCreatorText, isYouTubeBoilerplateText } from './creatorText';
import { hasCreatorLevelSemanticContext } from './providers/GeminiSemanticProvider';
import { assessRecognitionState } from './recognitionState';
import type { ContextualCompositionReport } from './contextualComposition';
import type { EvidenceCollectionReport } from './types';

function queryOnlyComposition(): ContextualCompositionReport {
  return {
    version: 'contextual-composition-v2',
    focus: 'QUERY_ONLY',
    observedFamilies: 0,
    informativeFamilies: 0,
    duplicateFamiliesCollapsed: 0,
    tradingFamilies: 0,
    tradingCoreFamilies: 0,
    tradingAdjacentFamilies: 0,
    financeAdjacentFamilies: 0,
    unrelatedFamilies: 0,
    uninformativeFamilies: 0,
    alternativeFamilies: 0,
    neutralFamilies: 0,
    recentTradingFamilies: 0,
    recentAlternativeFamilies: 0,
    tradingCoverage: 0,
    alternativeCoverage: 0,
    financeCoverage: 0,
    unrelatedCoverage: 0,
    temporalCoverage: 'UNKNOWN',
    nonTitleTierAFamilies: 0,
    explicitCreatorTrading: false,
    explicitCreatorAlternative: false,
    namePriorTrading: false,
    familyClassifications: [],
    reasonCodes: ['QUERY_ONLY'],
  };
}

const emptyCollection = {
  sufficiency: 'INSUFFICIENT',
  sparseMetadata: true,
  degraded: false,
  fieldsPresent: [],
  reasonCodes: ['INSUFFICIENT_CLASSIFICATION_EVIDENCE'],
  providers: [],
  terminalNegativeSufficiency: { status: 'INSUFFICIENT' },
} as unknown as EvidenceCollectionReport;

test('creator context excludes activity metadata, country, title and boilerplate', () => {
  assert.equal(hasMeaningfulCreatorFields({
    description: 'Share your videos with friends, family, and the world',
    video_titles: [],
  }), false);
  assert.equal(hasMeaningfulCreatorFields({ description: 'NQ futures trader.' }), true);
  assert.equal(hasMeaningfulCreatorFields({ description: 'Welcome to my channel!' }), false);
  assert.equal(hasMeaningfulCreatorText('Subscribe'), false);
  assert.equal(hasMeaningfulCreatorText('ES/NQ day trading, live executions.'), true);
  assert.equal(hasMeaningfulCreatorFields({ visual_evidence: [{ description: 'live futures chart with entries' }] }), true);
});

test('short real bio is creator context even in retrieval-only stage zero', () => {
  const input = {
    channel_name: 'Sk Trader',
    description: 'NQ trader',
    search_match_context: { type: 'VIDEO' as const, title: 'NQ setup' },
    enrichment_stage: 0,
  };
  assert.equal(hasCreatorLevelSemanticContext(input), true);
  assert.equal(hasCreatorLevelSemanticContext({
    ...input,
    description: 'Share your videos with friends, family, and the world',
    videos: [{ title: 'retrieval-selected match' }],
    video_titles: ['retrieval-selected match'],
  }), false);
});

test('QUERY_ONLY waits for semantic when creator context exists and enriches otherwise', () => {
  const base = {
    composition: queryOnlyComposition(),
    evidence: [],
    collection: emptyCollection,
    lifecycleAction: 'ENRICH' as const,
    semanticAvailable: true,
    minimumPositiveWeightTrading: 1,
    minimumTradingScore: 1,
  };
  const withContext = assessRecognitionState({ ...base, hasCreatorContext: true });
  assert.equal(withContext.state, 'QUERY_ONLY');
  assert.equal(withContext.semanticPolicy, 'BOUNDED_WAIT');
  assert.equal(withContext.semanticSkippedReason, null);

  const withoutContext = assessRecognitionState({ ...base, hasCreatorContext: false });
  assert.equal(withoutContext.state, 'QUERY_ONLY');
  assert.equal(withoutContext.semanticPolicy, 'ENRICH');
});

test('auto-generated music - Topic descriptions are not creator-authored bios', () => {
  const bio = 'Provided to YouTube by Universal Music Group\n\nLimp Bizkit - Break Stuff\n\nAuto-generated by YouTube.';
  assert.equal(isYouTubeBoilerplateText(bio), true);
  assert.equal(hasMeaningfulCreatorText(bio), false);
  assert.equal(hasMeaningfulCreatorFields({ description: bio }), false);
});
